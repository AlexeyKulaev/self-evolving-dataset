def write_report(cfg):
    state, _ = load_state(cfg)
    lines = ["# Отчёт запуска", "", f"Завершён: {state['complete']}",
             f"Этапов: {state['stage']}", f"Предъявлений: {state['seen_examples']}",
             f"Обработанных обучающих токенов: {state['seen_tokens']}",
             f"Семантический backend: {cfg['teacher']['backend']}",
             f"Модель учителя: {cfg['teacher']['model']} / {cfg['teacher']['reasoning_effort']} / {cfg['teacher']['service_tier']}",
             "", "| Домен | Статус | Accuracy | Причина выхода | Пул | Архив |",
             "|---|---|---:|---|---:|---:|"]
    for key in state["order"]:
        d = state["domains"][key]
        acc = f"{d['history'][-1]['accuracy']:.4f}" if d["history"] else "—"
        lines.append(f"| {key} | {d['status']} | {acc} | {d['exit_reason'] or '—'} | {len(d['pool'])} | {len(d['archive'])} |")
    root = Path(cfg["paths"]["output"])
    for method in ("adaptive", "baseline"):
        path = root / f"test-{method}.json"
        if path.exists():
            result = read_json(path)
            lines.extend(["", f"Test {method}: accuracy={result['accuracy']:.4f}, n={result['count']}, hash={result['test_hash']}."])
    lines.extend(["", ASSUMPTIONS])
    path = root / "report.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
